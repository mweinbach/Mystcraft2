"""Translate the inherited proxy and system CA trust into local Gradle settings."""
import os
from pathlib import Path
from urllib.parse import urlsplit

root = Path(__file__).resolve().parents[1]
settings = ["# Generated by scripts/java_network.py. Do not put credentials here."]
for protocol in ("http", "https"):
    address = os.environ.get(f"{protocol.upper()}_PROXY") or os.environ.get(f"{protocol}_proxy")
    if not address:
        continue
    proxy = urlsplit(address)
    if proxy.username or proxy.password:
        raise SystemExit("Authenticated proxy URLs need a supported local Java credential configuration.")
    if proxy.scheme not in {"http", "https"} or not proxy.hostname:
        raise SystemExit("Unsupported proxy URL.")
    settings += [f"systemProp.{protocol}.proxyHost={proxy.hostname}",
                 f"systemProp.{protocol}.proxyPort={proxy.port or (443 if proxy.scheme == 'https' else 80)}"]
settings += ["systemProp.http.nonProxyHosts=localhost|127.*|[::1]"]
# Debian's Java CA store includes the managed environment's proxy CA.
trust_store = Path("/etc/ssl/certs/java/cacerts")
if trust_store.is_file():
    settings.append(f"systemProp.javax.net.ssl.trustStore={trust_store}")
target = root / ".local/gradle/gradle.properties"
target.parent.mkdir(parents=True, exist_ok=True)
content = "\n".join(settings) + "\n"
if not target.exists() or target.read_text() != content:
    target.write_text(content)
