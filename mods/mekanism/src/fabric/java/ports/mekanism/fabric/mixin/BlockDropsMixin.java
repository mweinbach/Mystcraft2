package ports.mekanism.fabric.mixin;

import java.util.function.Supplier;
import net.minecraft.world.entity.item.ItemEntity;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.Block;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/**
 * Blocks drop nothing while their level restores block snapshots, as on Forge.
 */
@Mixin(Block.class)
public abstract class BlockDropsMixin {

    @Inject(method = "popResource(Lnet/minecraft/world/level/Level;Ljava/util/function/Supplier;Lnet/minecraft/world/item/ItemStack;)V", at = @At("HEAD"),
          cancellable = true)
    private static void mekanism$skipWhileRestoring(Level level, Supplier<ItemEntity> itemEntity, ItemStack stack, CallbackInfo ci) {
        if (level.isRestoringBlockSnapshots()) {
            ci.cancel();
        }
    }
}
