package ports.extremereactors.corelib.world;

import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.core.SectionPos;
import net.minecraft.core.particles.ParticleOptions;
import net.minecraft.util.RandomSource;
import net.minecraft.world.level.BlockGetter;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.LevelReader;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.block.state.BlockState;

import javax.annotation.Nullable;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;
import java.util.stream.StreamSupport;

public final class WorldHelper {

    //region chunks

    public static int getChunkXFromBlock(final BlockPos position) {
        return SectionPos.blockToSectionCoord(position.getX());
    }

    public static int getChunkZFromBlock(final BlockPos position) {
        return SectionPos.blockToSectionCoord(position.getZ());
    }

    //endregion
    //region block entities

    /**
     * @return the block entity at the given position, if its chunk is loaded. Unloaded chunks are never loaded or
     * generated by this call.
     */
    public static Optional<BlockEntity> getTile(final BlockGetter world, final BlockPos position) {
        return Optional.ofNullable(getLoadedTile(world, position));
    }

    @Nullable
    public static BlockEntity getLoadedTile(final BlockGetter world, final BlockPos position) {

        if (world instanceof LevelReader && !isLoaded((LevelReader) world, position)) {
            return null;
        }

        return world.getBlockEntity(position);
    }

    @Nullable
    public static BlockEntity getLoadedTile(final ChunkCache cache, final BlockPos position) {
        return cache.getLoadedBlockEntity(position);
    }

    public static Stream<BlockEntity> getTilesFrom(final BlockGetter world, final Iterable<BlockPos> positions) {
        return StreamSupport.stream(positions.spliterator(), false)
                .map(position -> getLoadedTile(world, position))
                .filter(Objects::nonNull);
    }

    public static Stream<BlockEntity> getTilesFrom(final BlockGetter world, final BlockPos... positions) {
        return Stream.of(positions)
                .map(position -> getLoadedTile(world, position))
                .filter(Objects::nonNull);
    }

    //endregion
    //region neighbors

    public static NeighboringPositions getNeighboringPositions(final BlockPos center) {
        return new NeighboringPositions(center);
    }

    /**
     * Fill the provided array with the six positions adjacent to the center, in {@link Direction} order.
     */
    public static BlockPos[] getNeighboringPositionsList(final BlockPos center, final BlockPos[] positions) {

        final Direction[] directions = Direction.values();

        if (positions.length < directions.length) {
            throw new IllegalArgumentException("The positions array must have room for " + directions.length + " elements");
        }

        for (int i = 0; i < directions.length; ++i) {
            positions[i] = center.relative(directions[i]);
        }

        return positions;
    }

    //endregion
    //region notifications

    /**
     * Ask the level to resend the block at the given position to the clients (on the server) or to re-render it
     * (on the client).
     */
    public static void notifyBlockUpdate(final Level world, final BlockPos position) {

        final BlockState state = world.getBlockState(position);

        world.sendBlockUpdated(position, state, state, Block.UPDATE_ALL);
    }

    public static void notifyBlockUpdate(final Level world, final BlockPos position, final BlockState oldState,
                                         final BlockState newState) {
        world.sendBlockUpdated(position, oldState, newState, Block.UPDATE_ALL);
    }

    public static void notifyNeighborsOfStateChange(final Level world, final BlockPos position, final Block blockType) {
        world.updateNeighborsAt(position, blockType);
    }

    //endregion
    //region particles

    /**
     * Spawn between minCount and maxCount particles near the given block. Each particle is placed at the block
     * center, moved half a block along the offset and jittered a little. Only does something on the client.
     */
    public static void spawnVanillaParticles(final Level world, final ParticleOptions particle,
                                             final int minCount, final int maxCount,
                                             final int x, final int y, final int z,
                                             final int offsetX, final int offsetY, final int offsetZ) {

        if (!world.isClientSide()) {
            return;
        }

        final RandomSource random = world.getRandom();
        final int count = minCount >= maxCount ? minCount : minCount + random.nextInt(maxCount - minCount + 1);

        for (int i = 0; i < count; ++i) {

            final double px = x + 0.5 + offsetX * 0.5 + (random.nextDouble() - 0.5) * 0.6;
            final double py = y + 0.5 + offsetY * 0.5 + (random.nextDouble() - 0.5) * 0.6;
            final double pz = z + 0.5 + offsetZ * 0.5 + (random.nextDouble() - 0.5) * 0.6;

            world.addParticle(particle, px, py, pz, 0.0, 0.0, 0.0);
        }
    }

    //endregion
    //region internals

    private static boolean isLoaded(final LevelReader world, final BlockPos position) {
        return world instanceof Level ? ((Level) world).isLoaded(position) : world.hasChunkAt(position);
    }

    private WorldHelper() {
    }

    //endregion
}
